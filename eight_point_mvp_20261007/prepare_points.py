"""Prepare the eight taught endpoints offline. Never opens a serial port."""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from read_handle_teach import decode_record

EXPECTED_SHA256 = "1f5d59c95b96d6346eb3244547a0aa847e4adb74b029b92486e0f6c456744c22"


def main():
    source = ROOT / "validation_runs/readout_20261005_180008/eight_points.bin"
    original_json = json.loads(source.with_suffix(".json").read_text(encoding="utf-8"))
    blob = source.read_bytes()
    digest = hashlib.sha256(blob).hexdigest()
    if digest != EXPECTED_SHA256:
        raise ValueError("The source differs from the verified eight-point backup")
    record = decode_record(blob)  # checks format, CRC and encoder bounds
    if not record["complete"] or len(record["poses"]) != 8:
        raise ValueError("All eight points are required")
    if record["poses"] != original_json["poses"]:
        raise ValueError("Binary and JSON endpoints disagree")

    out = Path(__file__).resolve().parent / "data"
    out.mkdir(exist_ok=True)
    preserved = out / "eight_points_original.bin"
    if preserved.exists() and preserved.read_bytes() != blob:
        raise ValueError("Refusing to overwrite a different preserved record")
    preserved.write_bytes(blob)
    points = [p["encoder_positions"] for p in record["poses"]]
    stages = [p["stage"] for p in record["poses"]]
    transitions = []
    for i in range(1, 8):
        delta = [b-a for a, b in zip(points[i-1], points[i])]
        transitions.append({"from_point": i, "to_point": i+1,
                            "encoder_delta": delta,
                            "max_abs_encoder_delta": max(map(abs, delta)),
                            "physical_path_validated": False})
    manifest = {"source": str(source), "sha256": digest, "crc_valid": True,
                "binary_json_agree": True, "point_count": 8,
                "joint_ids": [1, 2, 3, 4, 5, 6], "poses": record["poses"],
                "transitions": transitions,
                "units": "raw encoder counts; not XYZ or degrees",
                "current_official_firmware_identified": False,
                "current_servo_calibration_compatible": None,
                "physical_path_validated": False, "playback_validated": False}
    (out / "points_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    lines = ["// Generated by prepare_points.py. Data only; no motion implementation.",
             "// Recheck encoder calibration and limits after firmware/servo changes.",
             "#pragma once", "#include <stdint.h>",
             "namespace eight_point_mvp {",
             f'constexpr char kSourceSha256[] = "{digest}";',
             "constexpr uint8_t kPointCount = 8;",
             "constexpr uint8_t kJointCount = 6;",
             "constexpr int16_t kEncoderPositions[8][6] = {"]
    for name, values in zip(stages, points):
        lines.append("    {"+", ".join(map(str, values))+"}, // "+name)
    lines += ["};", "} // namespace eight_point_mvp", ""]
    (out / "TaughtPoints.h").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"crc_valid": True, "sha256": digest, "point_count": 8,
                      "max_adjacent_deltas": [t["max_abs_encoder_delta"] for t in transitions],
                      "output": str(out), "motion_sent": False}, indent=2))


if __name__ == "__main__":
    main()
